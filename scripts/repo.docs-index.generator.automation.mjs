function readText(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function assertAllowedGeneratedReadmeOutput(filePath) {
  const resolved = path.resolve(filePath);

  if (!GENERATED_README_OUTPUTS.has(resolved)) {
    throw new Error(
      `Unexpected generated README output outside declared automation margins: ${resolved}`,
    );
  }
}

function writeText(filePath, content) {
  assertAllowedGeneratedReadmeOutput(filePath);

  if (!isCheckMode) {
    fs.writeFileSync(filePath, content);
    return;
  }

  if (!fs.existsSync(filePath)) {
    generatedReadmeDriftErrors.push(
      `${filePath} is missing. Run pnpm docs:generate.`,
    );
    return;
  }

  const currentContent = readText(filePath);
  if (currentContent !== content) {
    generatedReadmeDriftErrors.push(
      `${filePath} is stale. Run pnpm docs:generate.`,
    );
  }
}

function validateReadmeMatrix() {
  const actualOutputs = README_MATRIX.map((entry) =>
    path.resolve(entry.outputPath),
  );

  if (actualOutputs.length !== GENERATED_README_OUTPUTS.size) {
    throw new Error("README matrix must declare exactly ten D1/D2/D3 outputs.");
  }

  for (const outputPath of actualOutputs) {
    if (!GENERATED_README_OUTPUTS.has(outputPath)) {
      throw new Error(
        `Unexpected generated README output outside declared automation margins: ${outputPath}`,
      );
    }
  }
}

function readmeHeader(title) {
  return [
    GENERATED_README_MARKER,
    "",
    `# ${title}`,
    "",
    GENERATED_README_NOTICE,
    "",
    "**Generated area:** declared README automation margin.",
    "",
    GENERATED_README_SCOPE_REMINDER,
  ];
}

function parseHeaderMetadata(content) {
  const header = content.split(/\r?\n/).slice(0, 20).join("\n");
  const metadata = new Map();

  for (const match of header.matchAll(
    /@afenda-(owner|subject|artifact|boundary|status|trace)\s+([^\s]+)/g,
  )) {
    metadata.set(match[1], match[2]);
  }

  const descriptionMatch = header.match(/@afenda-description\s+(.+)/);
  if (descriptionMatch?.[1]) {
    metadata.set("description", descriptionMatch[1].trim());
  }

  return metadata;
}

function validateEnvelope(content, filePathForError = "script") {
  const annotations = parseHeaderMetadata(content);
  const header = content.split(/\r?\n/).slice(0, 20).join("\n");

  if (!header.includes("@afenda-envelope")) {
    throw new Error(`${filePathForError} missing @afenda-envelope marker.`);
  }

  const required = [
    "owner",
    "subject",
    "artifact",
    "boundary",
    "description",
    "status",
    "trace",
  ];
  const missing = required.filter((entry) => !annotations.has(entry));

  if (missing.length > 0) {
    throw new Error(
      `${filePathForError} missing required @afenda fields: ${missing.join(", ")}.`,
    );
  }

  const status = annotations.get("status");
  if (!ALLOWED_STATUSES.has(status)) {
    throw new Error(
      `${filePathForError} has invalid @afenda-status "${status}". Allowed: draft, approved, deprecated.`,
    );
  }

  const boundary = annotations.get("boundary");
  if (!ALLOWED_BOUNDARIES.has(boundary)) {
    throw new Error(
      `${filePathForError} has invalid @afenda-boundary "${boundary}". Allowed: ${[...ALLOWED_BOUNDARIES].join(", ")}.`,
    );
  }
}

function normalizeTitle(fileName, markdown) {
  const firstLine = markdown
    .split(/\r?\n/)
    .find((line) => line.trim().length > 0);

  if (!firstLine) return fileName.replace(/\.md$/, "");
  if (firstLine.startsWith("# ")) return firstLine.replace(/^#\s*/, "").trim();

  return fileName.replace(/\.md$/, "");
}

function markdownLinkLabel(value) {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/\[/g, "\\[")
    .replace(/\]/g, "\\]")
    .replace(/_/g, "\\_");
}

function listAdrs() {
  const entries = fs
    .readdirSync(adrDir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md"));

  const records = [];

  for (const entry of entries) {
    if (entry.name === "README.md") continue;
    const filePath = path.join(adrDir, entry.name);
    const markdown = readText(filePath);
    const title = normalizeTitle(entry.name, markdown);
    records.push({ name: entry.name, title });
  }

  return records.sort((a, b) => a.name.localeCompare(b.name));
}

function listMarkdownFiles(dir) {
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".md"));

  const records = [];

  for (const entry of entries) {
    if (entry.name === "README.md") continue;
    const filePath = path.join(dir, entry.name);
    const markdown = readText(filePath);
    const title = normalizeTitle(entry.name, markdown);
    records.push({ name: entry.name, title });
  }

  return records.sort((a, b) => a.name.localeCompare(b.name));
}

function listGuidelineGroups() {
  return fs
    .readdirSync(guidelineDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

function listChildDirectories(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

function listSourceFiles(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter(
      (entry) =>
        entry.isFile() &&
        /\.(css|js|jsx|ts|tsx)$/.test(entry.name) &&
        entry.name !== "README.md",
    )
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b));
}

function writeAdrIndex(config, entries) {
  const lines = [
    ...readmeHeader(config.title),
    "",
    config.purpose,
    "",
    "Records:",
    "",
    ...entries.map(
      ({ name, title }) =>
        `- [${markdownLinkLabel(name)}](./${name}) — ${title}`,
    ),
    "",
    "- [Documentation home](../README.md)",
  ];

  writeText(config.outputPath, `${lines.join("\n")}\n`);
}

function writeGuidelineGroupIndex(config, entries) {
  const lines = [
    ...readmeHeader(config.title),
    "",
    config.purpose,
    "",
    "Guidelines:",
    "",
    ...entries.map(
      ({ name, title: entryTitle }) =>
        `- [${markdownLinkLabel(name)}](./${name}) — ${entryTitle}`,
    ),
    "",
    "- [Guidelines home](../README.md)",
  ];

  writeText(config.outputPath, `${lines.join("\n")}\n`);
}

function writeGuidelineRootIndex(config, groups) {
  const lines = [
    ...readmeHeader(config.title),
    "",
    config.purpose,
    "",
    "Guideline groups:",
    "",
    ...groups.map((group) => `- [${markdownLinkLabel(group)}/](./${group}/)`),
    "",
    "- [Project documentation](../docs/README.md)",
  ];

  writeText(config.outputPath, `${lines.join("\n")}\n`);
}

function writeSourceRootIndex(config, groups) {
  const lines = [
    ...readmeHeader(config.title),
    "",
    config.purpose,
    "",
    "Source groups:",
    "",
    ...groups.map((group) => `- [${markdownLinkLabel(group)}/](./${group}/)`),
  ];

  writeText(config.outputPath, `${lines.join("\n")}\n`);
}

function writeSourceModuleIndex(config, entries) {
  const groupLines =
    entries.groups.length > 0
      ? [
          "Source groups:",
          "",
          ...entries.groups.map(
            (group) => `- [${markdownLinkLabel(group)}/](./${group}/)`,
          ),
          "",
        ]
      : [];
  const fileLines =
    entries.files.length > 0
      ? [
          "Source files:",
          "",
          ...entries.files.map(
            (file) => `- [${markdownLinkLabel(file)}](./${file})`,
          ),
        ]
      : ["Source files:", "", "- None"];
  const lines = [
    ...readmeHeader(config.title),
    "",
    config.purpose,
    "",
    ...groupLines,
    ...fileLines,
  ];

  writeText(config.outputPath, `${lines.join("\n")}\n`);
}

function writeRootReadme(config, entries) {
  if (!fs.existsSync(rootReadmeSourcePath)) {
    throw new Error(
      `Missing root README source template: ${rootReadmeSourcePath}`,
    );
  }

  const template = readText(rootReadmeSourcePath).trimEnd();
  const [titleLine, ...templateBodyLines] = template.split(/\r?\n/);
  const bodyLines = [...templateBodyLines];

  if (!titleLine?.startsWith("# ")) {
    throw new Error(
      "Root README source template must start with a level-one heading.",
    );
  }

  while (bodyLines[0] === "") {
    bodyLines.shift();
  }

  const lines = [
    GENERATED_README_MARKER,
    "",
    titleLine,
    "",
    GENERATED_README_NOTICE,
    "",
    "**Generated area:** root README template automation margin.",
    "",
    "**Source template:** `docs/source/root-readme.md`.",
    "",
    ...bodyLines,
    "",
    "## Generated Navigation",
    "",
    config.purpose,
    "",
    "- [Project documentation index](docs/README.md)",
    "- [Guideline index](.guideline/README.md)",
    "- [Feature source index](src/features/README.md)",
    "- [Component source index](src/components/README.md)",
    `- ADR records indexed: ${entries.length}`,
  ];

  writeText(config.outputPath, `${lines.join("\n")}\n`);
}

function writeDocsReadme(config, entries) {
  const snapshotDate = process.env["AFENDA_DOCS_SNAPSHOT_DATE"];
  const lines = [
    ...readmeHeader(config.title),
    "",
    config.purpose,
    "",
    `Repository: \`${repoRoot}\``,
    ...(snapshotDate ? ["", `Snapshot date: \`${snapshotDate}\``] : []),
    "",
    "## Core Documentation",
    "",
    "- [README](../README.md)",
    "- [root README source](./source/root-readme.md)",
    "- [architecture.md](./architecture.md)",
    "- [atc.md](./atc.md)",
    "- [automation-contract.md](./automation-contract.md)",
    "- [adr/](./adr)",
    "- [guideline index](../.guideline/README.md)",
    "- [feature source index](../src/features/README.md)",
    "- [component source index](../src/components/README.md)",
    "",
    "## ADR Catalog",
    "",
    ...entries.map(
      ({ name, title }) =>
        `- [${markdownLinkLabel(name)}](./adr/${name}) — ${title}`,
    ),
    "",
    "## Maintenance",
    "",
    "Regenerate this index after ADR changes:",
    "",
    "```bash",
    "pnpm docs:generate",
    "```",
  ];

  writeText(config.outputPath, `${lines.join("\n")}\n`);
}

function getReadmeConfig(mode) {
  const config = README_MATRIX.find((entry) => entry.mode === mode);
  if (!config) {
    throw new Error(`Missing README matrix entry for mode "${mode}".`);
  }

  return config;
}

function getGuidelineGroupConfig(sourceDir) {
  const config = README_MATRIX.find(
    (entry) =>
      entry.mode === "guideline-group" && entry.sourceDir === sourceDir,
  );
  if (!config) {
    throw new Error(
      `Missing README matrix entry for guideline source "${sourceDir}".`,
    );
  }

  return config;
}

function getReadmeConfigBySource(sourceDir) {
  const config = README_MATRIX.find((entry) => entry.sourceDir === sourceDir);
  if (!config) {
    throw new Error(`Missing README matrix entry for source "${sourceDir}".`);
  }

  return config;
}

function main() {
  validateReadmeMatrix();

  const requiredDirs = README_MATRIX.map((entry) => entry.sourceDir);
  const missingDirs = requiredDirs.filter((dir) => !fs.existsSync(dir));
  if (missingDirs.length > 0) {
    throw new Error(
      `Expected documentation directories to exist: ${missingDirs.join(", ")}.`,
    );
  }

  const fileContent = readText(fileURLToPath(import.meta.url));
  validateEnvelope(
    fileContent,
    "scripts/repo.docs-index.generator.automation.mjs",
  );

  const adrEntries = listAdrs();
  const guidelineGroups = listGuidelineGroups();
  const nextjsGuidelines = listMarkdownFiles(guidelineNextjsDir);
  const reactAriaGuidelines = listMarkdownFiles(guidelineReactAriaDir);
  const featureGroups = listChildDirectories(featuresDir);
  const workbenchFeatureEntries = {
    groups: listChildDirectories(workbenchFeatureDir),
    files: listSourceFiles(workbenchFeatureDir),
  };
  const componentGroups = listChildDirectories(componentsDir);
  const uiComponentEntries = {
    groups: listChildDirectories(uiComponentsDir),
    files: listSourceFiles(uiComponentsDir),
  };

  writeRootReadme(getReadmeConfig("root"), adrEntries);
  writeAdrIndex(getReadmeConfig("adr"), adrEntries);
  writeGuidelineRootIndex(getReadmeConfig("guideline-root"), guidelineGroups);
  writeGuidelineGroupIndex(
    getGuidelineGroupConfig(guidelineNextjsDir),
    nextjsGuidelines,
  );
  writeGuidelineGroupIndex(
    getGuidelineGroupConfig(guidelineReactAriaDir),
    reactAriaGuidelines,
  );
  writeDocsReadme(getReadmeConfig("docs"), adrEntries);
  writeSourceRootIndex(getReadmeConfigBySource(featuresDir), featureGroups);
  writeSourceModuleIndex(
    getReadmeConfigBySource(workbenchFeatureDir),
    workbenchFeatureEntries,
  );
  writeSourceRootIndex(getReadmeConfigBySource(componentsDir), componentGroups);
  writeSourceModuleIndex(
    getReadmeConfigBySource(uiComponentsDir),
    uiComponentEntries,
  );

  if (isCheckMode) {
    if (generatedReadmeDriftErrors.length > 0) {
      console.error("Generated README drift check failed:\n");
      for (const error of generatedReadmeDriftErrors) {
        console.error(`- ${error}`);
      }
      process.exit(1);
    }

    console.log(
      `Generated README drift check passed for ${GENERATED_README_OUTPUTS.size} output(s).`,
    );
    return;
  }

  console.log(
    `Regenerated docs index with ${adrEntries.length} ADR record(s), ${nextjsGuidelines.length} Next.js guideline(s), ${reactAriaGuidelines.length} React Aria guideline(s), ${featureGroups.length} feature group(s), and ${componentGroups.length} component group(s).`,
  );
}

main();
